import hashlib
import os
import re
from pathlib import Path

import chromadb
from langchain_google_genai import GoogleGenerativeAIEmbeddings
from langchain_text_splitters import RecursiveCharacterTextSplitter

from app.llm import GEMINI_EMBEDDING_MODEL, require_gemini_api_key

# Use persistent storage in production, with the existing local path as default.
PROJECT_ROOT = Path(__file__).resolve().parents[2]

CHROMA_DIR = Path(
    os.getenv(
        "ARGUS_CHROMA_DIR",
        str(PROJECT_ROOT / "backend" / ".chroma"),
    )
).expanduser().resolve()

CHROMA_DIR.mkdir(parents=True, exist_ok=True)

SUPPORTED_EXTENSIONS = {
    ".py", ".js", ".jsx", ".ts", ".tsx",
    ".java", ".go", ".rs", ".cpp", ".c",
    ".h", ".cs", ".php", ".rb", ".sql",
    ".html", ".css", ".json", ".md", ".yaml", ".yml",
}

IGNORED_DIRS = {
    ".git", ".venv", "venv", "node_modules",
    "dist", "build", "__pycache__", ".chroma",
}

MAX_FILE_BYTES = 300_000
MAX_FILES = 500
MAX_CHUNK_CHARS = 1000
CHUNK_OVERLAP = 150

STOP_WORDS = {
    "the", "a", "an", "is", "are", "was", "were", "be",
    "to", "of", "in", "on", "for", "and", "or", "with",
    "how", "what", "where", "when", "why", "does", "do",
    "my", "your", "this", "that", "it", "using", "use",
    "explain", "show", "tell", "please", "actual",
}


class RepositoryRAG:
    def __init__(self):
        # A separate collection is required: vectors generated by different
        # embedding models are not compatible, even when dimensions match.
        # Create embedding clients lazily so the API and non-AI endpoints
        # can start even before an API key is configured.
        self._document_embeddings = None
        self._query_embeddings = None

        self.client = chromadb.PersistentClient(
            path=str(CHROMA_DIR)
        )

        self.collection = self.client.get_or_create_collection(
            name="argus_gemini_code_v1",
            metadata={"hnsw:space": "cosine"},
        )

        self.splitter = RecursiveCharacterTextSplitter(
            chunk_size=MAX_CHUNK_CHARS,
            chunk_overlap=CHUNK_OVERLAP,
        )

    def _get_document_embeddings(self):
        if self._document_embeddings is None:
            self._document_embeddings = GoogleGenerativeAIEmbeddings(
                model=GEMINI_EMBEDDING_MODEL,
                google_api_key=require_gemini_api_key(),
                task_type="RETRIEVAL_DOCUMENT",
                output_dimensionality=768,
            )
        return self._document_embeddings

    def _get_query_embeddings(self):
        if self._query_embeddings is None:
            self._query_embeddings = GoogleGenerativeAIEmbeddings(
                model=GEMINI_EMBEDDING_MODEL,
                google_api_key=require_gemini_api_key(),
                task_type="RETRIEVAL_QUERY",
                output_dimensionality=768,
            )
        return self._query_embeddings

    @staticmethod
    def _repo_id(root: Path) -> str:
        """Create a stable identifier for a repository."""
        return str(root.resolve())

    @staticmethod
    def _tokenize(text: str) -> set[str]:
        """Extract searchable identifiers and words."""
        return {
            token.lower()
            for token in re.findall(
                r"[A-Za-z_][A-Za-z0-9_./-]*",
                text,
            )
            if len(token) > 1 and token.lower() not in STOP_WORDS
        }

    def _repository_files(self, repo_path: str):
        root = Path(repo_path).resolve()

        if not root.is_dir():
            raise ValueError("Repository path is not a directory.")

        files = []

        for path in root.rglob("*"):
            relative = path.relative_to(root)

            if any(part in IGNORED_DIRS for part in relative.parts):
                continue

            if not path.is_file():
                continue

            if path.suffix.lower() not in SUPPORTED_EXTENSIONS:
                continue

            try:
                if path.stat().st_size > MAX_FILE_BYTES:
                    continue

                content = path.read_text(
                    encoding="utf-8",
                    errors="replace",
                )
            except OSError:
                continue

            if content.strip():
                files.append((path, content))

            if len(files) >= MAX_FILES:
                break

        return root, files

    def index_repository(self, repo_path: str):
        root, files = self._repository_files(repo_path)
        repo_id = self._repo_id(root)

        documents = []
        metadatas = []
        ids = []

        # Include repository identity in every chunk ID.
        repo_hash = hashlib.sha256(
            repo_id.encode("utf-8")
        ).hexdigest()[:16]

        for path, content in files:
            relative_path = path.relative_to(root).as_posix()
            chunks = self.splitter.split_text(content)

            for number, chunk in enumerate(chunks):
                documents.append(chunk)
                metadatas.append({
                    "source": relative_path,
                    "repo": repo_id,
                })
                ids.append(
                    f"{repo_hash}::{relative_path}::{number}"
                )

        # Remove stale chunks for this repository only.
        self.collection.delete(
            where={"repo": repo_id}
        )

        batch_size = 64

        for start in range(0, len(documents), batch_size):
            end = start + batch_size
            batch_documents = documents[start:end]

            vectors = self._get_document_embeddings().embed_documents(
                batch_documents
            )

            self.collection.upsert(
                ids=ids[start:end],
                documents=batch_documents,
                metadatas=metadatas[start:end],
                embeddings=vectors,
            )

        return {
            "repository": repo_id,
            "files_indexed": len(files),
            "chunks_indexed": len(documents),
        }

    def search(
        self,
        repo_path: str,
        question: str,
        k: int = 4,
    ):
        root = Path(repo_path).resolve()

        if not root.is_dir():
            raise ValueError("Repository path is not a directory.")

        if not question.strip():
            raise ValueError("Question cannot be empty.")

        repo_id = self._repo_id(root)
        k = max(1, min(k, 20))

        # Restrict all retrieval to the selected repository.
        repo_chunks = self.collection.get(
            where={"repo": repo_id},
            include=[],
        )

        total = len(repo_chunks["ids"])

        if total == 0:
            return []

        # Semantic retrieval: find conceptually related code.
        query_vector = self._get_query_embeddings().embed_query(question)

        semantic_count = min(total, max(k * 4, 20))

        semantic_results = self.collection.query(
            query_embeddings=[query_vector],
            n_results=semantic_count,
            where={"repo": repo_id},
            include=["documents", "metadatas", "distances"],
        )

        # Gather semantic candidates and their ranks.
        candidates = {}

        semantic_docs = semantic_results.get("documents") or [[]]
        semantic_meta = semantic_results.get("metadatas") or [[]]
        semantic_distances = semantic_results.get("distances") or [[]]
        semantic_ids = semantic_results.get("ids") or [[]]

        for rank, (doc, metadata, distance, chunk_id) in enumerate(
            zip(
                semantic_docs[0],
                semantic_meta[0],
                semantic_distances[0],
                semantic_ids[0],
            ),
            start=1,
        ):
            candidates[chunk_id] = {
                "source": metadata.get("source", "Unknown source"),
                "content": doc,
                "distance": float(distance),
                "semantic_rank": rank,
            }

        # Keyword retrieval: also inspect indexed chunks for exact
        # identifiers, filenames, endpoints, and function names.
        # This helps when semantic search misses one side of a flow.
        all_chunks = self.collection.get(
            where={"repo": repo_id},
            include=["documents", "metadatas"],
        )

        query_tokens = self._tokenize(question)

        for chunk_id, doc, metadata in zip(
            all_chunks["ids"],
            all_chunks["documents"] or [],
            all_chunks["metadatas"] or [],
        ):
            source = metadata.get("source", "Unknown source")

            content_tokens = self._tokenize(doc)
            path_tokens = self._tokenize(source)

            content_overlap = (
                len(query_tokens & content_tokens)
                / max(1, len(query_tokens))
            )

            path_overlap = (
                len(query_tokens & path_tokens)
                / max(1, len(query_tokens))
            )

            # Small path bonus makes directly relevant files more
            # competitive without automatically selecting a filename.
            keyword_score = content_overlap + 0.75 * path_overlap

            existing = candidates.get(chunk_id)

            if existing is None:
                candidates[chunk_id] = {
                    "source": source,
                    "content": doc,
                    "distance": None,
                    "semantic_rank": None,
                    "keyword_score": keyword_score,
                }
            else:
                existing["keyword_score"] = keyword_score

        # Combine semantic rank and lexical relevance.
        # Exact terms can rescue chunks that semantic search ranked low.
        ranked = []

        for chunk_id, item in candidates.items():
            semantic_rank = item.get("semantic_rank")
            semantic_score = (
                1.0 / (60 + semantic_rank)
                if semantic_rank is not None
                else 0.0
            )

            keyword_score = item.get("keyword_score", 0.0)
            combined_score = semantic_score + keyword_score

            ranked.append((
                combined_score,
                chunk_id,
                item,
            ))

        ranked.sort(
            key=lambda entry: entry[0],
            reverse=True,
        )

        matches = []

        for score, chunk_id, item in ranked[:k]:
            matches.append({
                "source": item["source"],
                "content": item["content"],
                "distance": item.get("distance"),
                "score": round(score, 4),
            })

        return matches
